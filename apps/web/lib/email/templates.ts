function sectionTitle(text: string, color = BLUE) {
  return `<p style="margin:24px 0 12px;font-size:11px;font-weight:800;color:${color};text-transform:uppercase;letter-spacing:0.1em;">${text}</p>`
}

function statRow(stats: { label: string; value: string | number; color?: string }[]) {
  const cells = stats.map(s => `
    <td style="width:${100/stats.length}%;text-align:center;padding:16px 8px;background:#f8fafc;border-radius:8px;">
      <div style="font-size:24px;font-weight:900;color:${s.color ?? NAVY};">${s.value}</div>
      <div style="font-size:11px;font-weight:600;color:#64748b;text-transform:uppercase;letter-spacing:0.06em;margin-top:4px;">${s.label}</div>
    </td>
  `).join('<td style="width:8px;"></td>')
  return `<table width="100%" cellpadding="0" cellspacing="0"><tr>${cells}</tr></table>`
}

function scoreChip(score: number | null) {
  const c = scoreColor(score)
  return `<span style="display:inline-block;padding:2px 10px;border-radius:99px;font-size:12px;font-weight:800;color:${c};background:${c}18;border:1px solid ${c}40;">${score ?? '—'}</span>`
}

function dataTable(headers: string[], rows: string[][]): string {
  const headerRow = headers.map(h =>
    `<th style="padding:10px 12px;text-align:left;font-size:11px;font-weight:800;color:#64748b;text-transform:uppercase;letter-spacing:0.06em;border-bottom:2px solid #e2e8f0;">${h}</th>`
  ).join('')

  const bodyRows = rows.map((row, i) => {
    const cells = row.map((cell, ci) =>
      `<td style="padding:10px 12px;font-size:13px;color:#1e293b;border-bottom:1px solid #f1f5f9;${ci === 0 ? 'font-weight:600;' : ''}">${cell}</td>`
    ).join('')
    return `<tr style="background:${i % 2 === 0 ? '#ffffff' : '#f8fafc'};">${cells}</tr>`
  }).join('')

  return `<table width="100%" cellpadding="0" cellspacing="0" style="border-collapse:collapse;border:1px solid #e2e8f0;border-radius:8px;overflow:hidden;">
    <thead><tr style="background:#f8fafc;">${headerRow}</tr></thead>
    <tbody>${bodyRows || `<tr><td colspan="${headers.length}" style="padding:20px;text-align:center;color:#94a3b8;font-size:13px;">No data for this period.</td></tr>`}</tbody>
  </table>`
}

