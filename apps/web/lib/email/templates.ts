interface SCCall {
  id: string
  user_id: string
  score: number | null
  scorable: boolean
  created_at: string
  call_result: string | null
  contact_name?: string | null
  crm_link?: string | null
  agent?: { full_name: string | null; agent_type: string } | null
}

const AGENT_TYPE_LABELS: Record<string, string> = {
  fus:      'Setters (FUS)',
  acq:      'Closers (ACQ)',
  tc:       'Transaction Coordinators (TC)',
  cc:       'Client Care (CC)',
  dispo:    'Disposition (Dispo)',
  dispo_fus:'Disposition Setters (Dispo FUS)',
  tca:      'Transaction Coordinator Assistants (TCA)',
  none:     'Unassigned',
}


export const SC_TYPE_ORDER = ['fus', 'acq', 'tc', 'cc', 'dispo', 'dispo_fus', 'tca', 'none']

function teamify(text: string): string {
  return text
    .replace(/\byou\b/gi,        'the team')
    .replace(/\byour\b/gi,       "the team's")
    .replace(/\bthe agent\b/gi,  'the team')
    .replace(/\bthe rep\b/gi,    'the team')
    .replace(/\bthey\b/gi,       'the team')
    .replace(/\btheir\b/gi,      "the team's")
}

// Extract raw strengths + actions from calls — exported so cron can clean them before passing back
export function extractTeamBullets(calls: SCCall[]): { strengths: string[]; actions: string[] } {
  const scorable  = calls.filter(c => c.scorable && c.score !== null)
  const strengths: string[] = []
  const actions:   string[] = []
  for (const c of scorable.slice(0, 20)) {
    const ev = (c as any).evaluation
    if (ev?.strengths) {
      for (const s of ev.strengths.slice(0, 2)) {
        if (s && !strengths.includes(s)) strengths.push(s)
      }
    }
    if (ev?.coaching_actions) {
      for (const a of ev.coaching_actions.slice(0, 2)) {
        if (a.action && !actions.includes(a.action)) actions.push(a.action)
      }
    }
  }
  return { strengths, actions }
}

export function scAgentTypeTeamTemplate(
  agentType: string,
  companyName: string,
  period: PeriodBounds,
  calls: SCCall[],
  reportLabel: string,
  cleanedStrengths?: string[],
  cleanedActions?: string[],
): string {
  const label        = AGENT_TYPE_LABELS[agentType] ?? agentType.toUpperCase()
  const scorable     = calls.filter(c => c.scorable && c.score !== null)
  const avgScore     = scorable.length ? Math.round(scorable.reduce((s, c) => s + c.score!, 0) / scorable.length) : null
  const scorableRate = calls.length ? Math.round((scorable.length / calls.length) * 100) : 0

  // Top reps leaderboard
  const repMap = new Map<string, { name: string; total: number; count: number }>()
  for (const c of scorable) {
    const name = c.agent?.full_name ?? 'Unknown'
    const ex   = repMap.get(c.user_id)
    ex ? (ex.total += c.score!, ex.count++) : repMap.set(c.user_id, { name, total: c.score!, count: 1 })
  }
  const topReps = Array.from(repMap.values())
    .map(r => ({ name: r.name, avg: Math.round(r.total / r.count), count: r.count }))
    .sort((a, b) => b.avg - a.avg)
    .slice(0, 8)

  // Use pre-cleaned bullets if provided, otherwise fall back to teamify() on raw
  const raw = extractTeamBullets(calls)
  const strengths = cleanedStrengths ?? raw.strengths.map(teamify)
  const actions   = cleanedActions   ?? raw.actions.map(teamify)

  // Recent scored calls
  const recent = [...scorable].sort((a, b) => new Date(b.created_at).getTime() - new Date(a.created_at).getTime()).slice(0, 10)

  const body = `
    <h2 style="margin:0 0 4px;font-size:22px;font-weight:900;color:#1e293b;">Sales Coach Team Report</h2>
    <p style="margin:0 0 4px;font-size:16px;font-weight:700;color:${BLUE};">${label}</p>
    <p style="margin:0 0 24px;font-size:14px;color:#64748b;">${companyName}</p>

    ${periodBadge(period, reportLabel)}

    ${sectionTitle('Team Overview')}
    ${statRow([
      { label: 'Total Calls',   value: calls.length,       color: NAVY  },
      { label: 'Avg Score',     value: avgScore ?? '—',    color: avgScore ? scoreColor(avgScore) : '#64748b' },
      { label: 'Scorable Rate', value: `${scorableRate}%`, color: BLUE  },
      { label: 'Scored Calls',  value: scorable.length,    color: GREEN },
    ])}

    ${topReps.length ? `
      ${sectionTitle('Top Reps')}
      ${dataTable(['#', 'Rep', 'Avg Score', 'Calls'], topReps.map((r, i) => [
        `${i + 1}`, r.name, scoreChip(r.avg), String(r.count),
      ]))}
    ` : ''}

    ${strengths.length ? `
      ${sectionTitle('What The Team Did Well', GREEN)}
      <ul style="margin:0;padding-left:20px;">
        ${strengths.map(s => `<li style="font-size:13px;color:#1e293b;margin-bottom:8px;line-height:1.5;">${s}</li>`).join('')}
      </ul>
    ` : ''}

    ${actions.length ? `
      ${sectionTitle('Team Coaching Actions', AMBER)}
      <ul style="margin:0;padding-left:20px;">
        ${actions.map(a => `<li style="font-size:13px;color:#1e293b;margin-bottom:8px;line-height:1.5;">${a}</li>`).join('')}
      </ul>
    ` : ''}

    ${recent.length ? `
      ${sectionTitle('Recent Scored Calls')}
      ${dataTable(['Date', 'Contact', 'Score', 'Result'], recent.map(c => {
        const name = c.contact_name ?? 'Unknown'
        const contact = c.crm_link
          ? `<a href="${c.crm_link}" target="_blank" rel="noopener noreferrer" style="color:${BLUE};font-weight:600;text-decoration:none;">${name}</a>`
          : `<span style="color:#1e293b;">${name}</span>`
        return [fmt(c.created_at), contact, scoreChip(c.score), c.call_result ?? '—']
      }))}
    ` : ''}
  `

  return wrap(
    `Sales Coach ${label} Team Report — ${period.label}`,
    `${calls.length} calls · Avg score ${avgScore ?? 'N/A'} · ${period.label}`,
    body,
  )
}

