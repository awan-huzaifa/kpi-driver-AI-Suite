function fmtUSD(n: number | null) {
  if (!n) return '—'
  return '$' + Math.round(n).toLocaleString()
}

function recColor(r: string | null) {
  if (!r) return '#64748b'
  const l = r.toLowerCase()
  if (l.includes('buy') || l.includes('strong')) return GREEN
  if (l.includes('pass') || l.includes('avoid')) return RED
  return AMBER
}

